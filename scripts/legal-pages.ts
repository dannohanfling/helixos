/**
 * Writes src/content/legal.ts from docs/legal/*.html (H-331): Scriba's six pages, word for word, with the cross-page links
 * turned into routes. Run after a page changes: `npx tsx --tsconfig tsconfig.json scripts/legal-pages.ts`. The unit test
 * (legal.test.ts) regenerates in memory and fails when the two differ, so a page can't change without its route changing.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { LEGAL_SLUGS, legalFromHtml } from "@/lib/engine/legal";

export function renderLegalModule(root: string): string {
  const pages = LEGAL_SLUGS.map((slug) => legalFromHtml(slug, readFileSync(join(root, "docs/legal", `${slug}.html`), "utf8")));
  const body = pages.map((p) => `  "${p.slug}": ${JSON.stringify({ slug: p.slug, title: p.title, description: p.description, html: p.html }, null, 2).replace(/\n/g, "\n  ")},`).join("\n");
  return `/* Generated by scripts/legal-pages.ts from docs/legal/*.html (H-331). Edit the HTML there, not this file. */\nimport type { LegalPage, LegalSlug } from "@/lib/engine/legal";\n\nexport const LEGAL_PAGES: Record<LegalSlug, LegalPage> = {\n${body}\n};\n`;
}

if (process.argv[1]?.endsWith("legal-pages.ts")) {
  const root = process.cwd();
  writeFileSync(join(root, "src/content/legal.ts"), renderLegalModule(root));
  console.log(`legal-pages: ${LEGAL_SLUGS.length} pages written to src/content/legal.ts`);
}
